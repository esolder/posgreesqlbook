-- =============================================
-- Проверочный запрос
-- =============================================
SELECT 
    o.id AS order_id,
    c.name AS client,
    c.phone,
    c.birth_date,
    f.name AS flower,
    col.name AS color,
    o.quantity,
    o.order_ts,
    o.status,
    ct.name AS city,
    ct.population
FROM orders o
JOIN clients c ON o.client_phone = c.phone
JOIN flowers f ON o.flower_id = f.id
JOIN colors col ON o.color_code = col.code
JOIN cities ct ON c.city_id = ct.id
ORDER BY o.order_ts
LIMIT 5;

-- =============================================
-- Дополнительный запрос: распределение по статусам
-- =============================================
SELECT status, COUNT(*) AS order_count
FROM orders
GROUP BY status
ORDER BY order_count DESC;
