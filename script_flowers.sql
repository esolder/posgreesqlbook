-- =============================================
-- Удаление таблиц (если существуют)
-- =============================================
DROP TABLE IF EXISTS orders;
DROP TABLE IF EXISTS clients;
DROP TABLE IF EXISTS cities;
DROP TABLE IF EXISTS colors;
DROP TABLE IF EXISTS flowers;

-- =============================================
-- Создание таблиц
-- =============================================

-- Таблица цветов
CREATE TABLE flowers (
    id SERIAL PRIMARY KEY,
    name TEXT NOT NULL,
    price NUMERIC(10,2) NOT NULL CHECK (price > 0)
);

-- Таблица оттенков (ключ — двухбуквенный код)
CREATE TABLE colors (
    code CHAR(2) PRIMARY KEY,
    name TEXT NOT NULL UNIQUE
);

-- Таблица городов (население может быть NULL)
CREATE TABLE cities (
    id SERIAL PRIMARY KEY,
    name TEXT NOT NULL UNIQUE,
    population INTEGER CHECK (population > 0)
);

-- Таблица клиентов (телефон — 9 цифр, без первой)
CREATE TABLE clients (
    phone TEXT PRIMARY KEY CHECK (phone ~ '^[0-9]{9}$'),
    name TEXT NOT NULL,
    city_id INTEGER NOT NULL,
    birth_date DATE
);

-- Таблица заказов (без внешних ключей, но со статусом)
CREATE TABLE orders (
    id SERIAL PRIMARY KEY,
    client_phone TEXT NOT NULL,
    flower_id INTEGER NOT NULL,
    color_code CHAR(2) NOT NULL,
    quantity INTEGER NOT NULL CHECK (quantity > 0),
    order_ts TIMESTAMP NOT NULL,
    status TEXT NOT NULL DEFAULT 'новый' CHECK (status IN ('новый', 'в доставке', 'доставлен', 'отменён'))
);

